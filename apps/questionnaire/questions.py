def _section(key, title, items, hint=""):
    questions = []
    for n, item in enumerate(items, 1):
        text, kind, *rest = item
        questions.append(
            Question(key=f"{key}_{n:02d}", text=text, kind=kind, reverse=bool(rest and rest[0]))
        )
    return Section(key=key, title=title, questions=tuple(questions), hint=hint)


